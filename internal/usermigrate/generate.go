package usermigrate

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/yakisoba0728/PgBase/internal/schema"
)

var validName = regexp.MustCompile(`^[a-z][a-z0-9]*(?:_[a-z0-9]+)*$`)
var validPackage = regexp.MustCompile(`^[a-z][a-z0-9_]*$`)

type Generated struct {
	ID       string
	Filename string
	Source   []byte
	Impact   schema.MigrationImpact
}

// Generate writes a compilable blank Go migration whose exact source bytes are
// embedded into its registration. O_EXCL keeps repeated invocations harmless.
func Generate(directory, name string, now time.Time) (string, error) {
	name = strings.ToLower(strings.TrimSpace(name))
	if !validName.MatchString(name) {
		return "", errors.New("migration name must use lowercase letters, digits, and underscores")
	}
	id := now.UTC().Format("20060102150405") + "_" + name
	filename := id + ".go"
	if err := os.MkdirAll(directory, 0o755); err != nil {
		return "", fmt.Errorf("create migration directory: %w", err)
	}
	path := filepath.Join(directory, filename)
	variable := "source" + id
	source := fmt.Sprintf(`package migrations

import (
	"context"
	_ "embed"

	"github.com/jackc/pgx/v5"
	"github.com/yakisoba0728/PgBase/pgbase"
)

//go:embed %s
var %s []byte

func init() {
	pgbase.RegisterUserMigration(pgbase.UserMigration{
		ID: %q, Source: %s,
		Up: func(ctx context.Context, tx pgx.Tx) error {
			// Write the forward migration with tx.Exec(ctx, ...).
			return nil
		},
		Down: func(ctx context.Context, tx pgx.Tx) error {
			// Reverse every change made by Up.
			return nil
		},
	})
}
`, filename, variable, id, variable)
	if err := writeExclusive(path, []byte(source)); err != nil {
		return "", err
	}
	return path, nil
}

// GenerateFromSnapshots writes a deterministic, executable schema migration.
func GenerateFromSnapshots(directory, packageName, name string, now time.Time, before, after []byte) (Generated, string, error) {
	name = strings.ToLower(strings.TrimSpace(name))
	if !validName.MatchString(name) {
		return Generated{}, "", errors.New("migration name must use lowercase letters, digits, and underscores")
	}
	id := now.UTC().Format("20060102150405") + "_" + name
	generated, err := GenerateSnapshotSource(id, packageName, before, after)
	if err != nil {
		return Generated{}, "", err
	}
	if err := os.MkdirAll(directory, 0o755); err != nil {
		return Generated{}, "", fmt.Errorf("create migration directory: %w", err)
	}
	path := filepath.Join(directory, generated.Filename)
	if err := writeExclusive(path, generated.Source); err != nil {
		return Generated{}, "", err
	}
	return generated, path, nil
}

// GenerateSnapshotSource returns exact source bytes without touching disk. It
// is shared by manual generation and the durable administrator recorder.
func GenerateSnapshotSource(id, packageName string, before, after []byte) (Generated, error) {
	if !validID.MatchString(id) {
		return Generated{}, errors.New("invalid migration ID")
	}
	if packageName == "" {
		packageName = "migrations"
	}
	if !validPackage.MatchString(packageName) {
		return Generated{}, errors.New("invalid Go package name")
	}
	canonicalBefore, err := schema.CanonicalMigrationSnapshot(before)
	if err != nil {
		return Generated{}, fmt.Errorf("canonicalize before snapshot: %w", err)
	}
	canonicalAfter, err := schema.CanonicalMigrationSnapshot(after)
	if err != nil {
		return Generated{}, fmt.Errorf("canonicalize after snapshot: %w", err)
	}
	impact, err := schema.AnalyzeMigrationSnapshots(canonicalBefore, canonicalAfter)
	if err != nil {
		return Generated{}, err
	}
	filename := id + ".go"
	variable := "source" + id
	beforeVariable := "beforeSnapshot" + id
	afterVariable := "afterSnapshot" + id
	downBody := "return pgbase.ApplyUserMigrationSnapshot(ctx, tx, " + afterVariable + ", " + beforeVariable + ")"
	if len(impact.Irreversible) != 0 {
		reasons := append([]string(nil), impact.Irreversible...)
		sort.Strings(reasons)
		downBody = "return &pgbase.IrreversibleMigrationError{Reason: " + strconv.Quote(strings.Join(reasons, "; ")) + "}"
	}
	comments := []string{"// Generated by PgBase from canonical collection snapshots.", "// Review this migration before committing it."}
	for _, warning := range impact.DataLoss {
		comments = append(comments, "// DATA LOSS: "+strings.ReplaceAll(warning, "\n", " "))
	}
	source := fmt.Sprintf(`package %s

import (
	"context"
	_ "embed"

	"github.com/jackc/pgx/v5"
	"github.com/yakisoba0728/PgBase/pgbase"
)

%s
//go:embed %s
var %s []byte

var %s = []byte(%s)
var %s = []byte(%s)

func init() {
	pgbase.RegisterUserMigration(pgbase.UserMigration{
		ID: %q, Source: %s,
		BeforeSnapshot: %s, AfterSnapshot: %s,
		IrreversibleReason: %q,
		Up: func(ctx context.Context, tx pgx.Tx) error {
			return pgbase.ApplyUserMigrationSnapshot(ctx, tx, %s, %s)
		},
		Down: func(ctx context.Context, tx pgx.Tx) error {
			%s
		},
	})
}
`, packageName, strings.Join(comments, "\n"), filename, variable,
		beforeVariable, strconv.Quote(string(canonicalBefore)), afterVariable, strconv.Quote(string(canonicalAfter)), id, variable,
		beforeVariable, afterVariable, strings.Join(impact.Irreversible, "; "), beforeVariable, afterVariable, downBody)
	return Generated{ID: id, Filename: filename, Source: []byte(source), Impact: impact}, nil
}

func writeExclusive(path string, source []byte) error {
	file, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if err != nil {
		return fmt.Errorf("create migration file: %w", err)
	}
	if _, err := file.Write(source); err != nil {
		_ = file.Close()
		return fmt.Errorf("write migration file: %w", err)
	}
	if err := file.Sync(); err != nil {
		_ = file.Close()
		return fmt.Errorf("sync migration file: %w", err)
	}
	if err := file.Close(); err != nil {
		return fmt.Errorf("close migration file: %w", err)
	}
	return nil
}
