import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { createMemoryRouter, RouterProvider } from "react-router";
import { afterEach, expect, it, vi } from "vitest";
import * as api from "../api/authCollections";
import { NewUserPane } from "./NewUserPane";
import { setLanguage } from "../i18n";
afterEach(() => { cleanup(); vi.restoreAllMocks(); });
it("submits a text ID, custom password, required false and nonempty file references", async () => {
  setLanguage("en");
  const field = (name: string, type: api.AuthFieldType, options?: Record<string, unknown>) => ({ name, type, required: true, unique: false, indexed: false, options });
  const collection: api.AuthCollection = { id: "c", name: "members", type: "auth", registrationEnabled: true, profileSchema: {}, recordId: { kind: "text" }, rules: { list: null, view: null, create: null, update: null, delete: null, auth: null, manage: null }, fields: [field("accepted", "boolean"), field("pin", "password"), field("photo", "file", { minSelect: 1 })] };
  vi.spyOn(api, "listAuthCollections").mockResolvedValue([collection]);
  vi.spyOn(api, "getAuthAdministration").mockResolvedValue({ policy: { minimumPasswordBytes: 12 } } as api.AuthAdministration);
  const create = vi.spyOn(api, "createAuthRecord").mockResolvedValue({ id: "Alice" } as api.AuthRecord);
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  const router = createMemoryRouter([{ path: "*", element: <NewUserPane onClose={vi.fn()} onCreated={vi.fn()} /> }]);
  render(<QueryClientProvider client={client}><RouterProvider router={router} /></QueryClientProvider>);
  await screen.findByLabelText(/^pin/);
  fireEvent.change(screen.getByLabelText(/^id/), { target: { value: "Alice" } });
  fireEvent.change(screen.getByRole("textbox", { name: /^Email/ }), { target: { value: "alice@example.test" } });
  fireEvent.change(screen.getByLabelText(/^Password/), { target: { value: "long-password-123" } });
  fireEvent.change(screen.getByLabelText(/^pin/), { target: { value: "secret-pin-123" } });
  fireEvent.change(screen.getByLabelText(/^photo/), { target: { value: '["00000000-0000-4000-8000-000000000001"]' } });
  fireEvent.submit(document.getElementById("auth-new-user")!);
  await waitFor(() => expect(create).toHaveBeenCalled());
  expect(create.mock.calls[0]).toEqual(["c", expect.objectContaining({ id: "Alice", fields: { accepted: false, pin: "secret-pin-123", photo: ["00000000-0000-4000-8000-000000000001"] } })]);
  cleanup(); client.clear();
});
